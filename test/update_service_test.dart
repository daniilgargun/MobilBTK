import 'package:flutter_test/flutter_test.dart';
import 'package:mobilapp/services/update_service.dart';

/// Сравнение версий решает, показывать ли диалог обновления. Ошибка здесь
/// либо прячет обновление навсегда, либо показывает диалог всем и всегда.
void main() {
  int cmp(String a, String b) => UpdateService.compareVersions(a, b);

  test('равные версии', () {
    expect(cmp('1.0.13', '1.0.13'), 0);
  });

  test('старшая часть важнее младшей', () {
    expect(cmp('1.0.13', '1.1.0'), lessThan(0));
    expect(cmp('2.0.0', '1.9.9'), greaterThan(0));
  });

  test('двузначные числа сравниваются как числа, а не как текст', () {
    // Строковое сравнение поставило бы "1.0.9" выше "1.0.10".
    expect(cmp('1.0.9', '1.0.10'), lessThan(0));
    expect(cmp('1.0.20', '1.0.3'), greaterThan(0));
  });

  test('разная длина: 1.1 равна 1.1.0', () {
    expect(cmp('1.1', '1.1.0'), 0);
    expect(cmp('1.1', '1.1.1'), lessThan(0));
  });

  test('номер сборки не влияет на сравнение', () {
    expect(cmp('1.0.13+17', '1.0.13'), 0);
    expect(cmp('1.0.13+1', '1.0.14+99'), lessThan(0));
  });

  test('пробелы по краям не мешают', () {
    expect(cmp(' 1.0.13 ', '1.0.13'), 0);
  });

  test('мусор считается нулём и не поднимает версию', () {
    // Иначе опечатка в консоли показала бы диалог обновления всем сразу.
    expect(cmp('1.0.13', 'Образование'), greaterThan(0));
    expect(cmp('1.0.13', '1.0.x'), greaterThan(0));
  });
}
