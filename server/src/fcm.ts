/**
 * Отправка «звонка в дверь» в тему FCM.
 *
 * Сообщение намеренно без полей `notification` и без содержимого расписания.
 * Причины две.
 *
 * Первая: сообщение с `notification` рисует сама система, своей иконкой и
 * мимо наших каналов и настроек. Уведомление должно выглядеть и вести себя
 * ровно так же, как то, что приложение показывает само.
 *
 * Вторая, главная: сервер не знает, кому какие изменения интересны. Разбор
 * и сравнение расписаний с фильтром по профилю уже есть в приложении,
 * покрыты тестами и работают. Повторять их на сервере — значит завести
 * второй парсер чужого HTML на другом языке, который надо чинить дважды при
 * каждом изменении вёрстки. Поэтому сервер сообщает единственный факт:
 * «страница изменилась», — а что с этим делать, решает приложение.
 *
 * Побочная выгода: одно сообщение на одну тему вместо сотни сообщений по
 * теме на группу. У бесплатного плана Cloudflare не больше пятидесяти
 * подзапросов на один запуск, и рассылка по группам в него бы не влезла.
 */

const ENDPOINT = 'https://fcm.googleapis.com/v1/projects';

export async function sendWakeUp(options: {
  projectId: string;
  accessToken: string;
  topic: string;
  pageHash: string;
}): Promise<void> {
  const response = await fetch(
    `${ENDPOINT}/${options.projectId}/messages:send`,
    {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${options.accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        message: {
          topic: options.topic,
          data: {
            type: 'schedule_changed',
            // Хэш нужен приложению, чтобы не запускать разбор дважды, если
            // одно и то же сообщение придёт повторно: FCM гарантирует
            // доставку хотя бы раз, а не ровно один раз.
            page_hash: options.pageHash,
          },
          android: {
            // Без высокого приоритета сообщение с одними данными не разбудит
            // приложение в Doze — то есть ровно тогда, когда оно и нужно.
            priority: 'HIGH',
            // Расписание меняется несколько раз в день; сообщение, не
            // доставленное за сутки, устарело — новое всё равно придёт.
            ttl: '86400s',
            // Новое сообщение отменяет предыдущее недоставленное: важен
            // только факт изменения, а не сколько раз оно случилось.
            collapse_key: 'schedule_changed',
          },
        },
      }),
    },
  );

  if (!response.ok) {
    throw new Error(
      `FCM отказал: ${response.status} ${await response.text()}`,
    );
  }
}
